String translate(String lang, String key, [Map<String, Object?> args = const {}]) {
  var s = _strings[lang]?[key] ?? _strings['en']![key] ?? key;
  args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

bool hasKey(String key) => _strings['en']!.containsKey(key);

class LangScope extends InheritedWidget {
  const LangScope({super.key, required this.lang, required super.child});
  final String lang;
  @override
  bool updateShouldNotify(LangScope old) => old.lang != lang;
}

extension L10n on BuildContext {
  String get lang => dependOnInheritedWidgetOfExactType<LangScope>()?.lang ?? 'en';
  String t(String key, [Map<String, Object?> args = const {}]) => translate(lang, key, args);
}
